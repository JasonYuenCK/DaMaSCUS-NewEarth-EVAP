# 2. 你的物理量（這裡用假數據示範，實際請換成密度/速度）
#    長度必須跟 r 一樣
y = np.linspace(13.0, 3.0, len(r))   # 例如密度從 13 降到 3 g/cm³

# 3. 去除重複的半徑點（平台段 r 相同會導致插值失敗）
#    方法：對相同 r 取平均
r_unique, idx = np.unique(r, return_index=True)
y_unique = np.array([y[r == ri].mean() for ri in r_unique])

# 4. 建立插值函數
#    - linear : 最安全，不會過衝
#    - pchip  : 單調三次，物理模擬常用，不會震盪
#    - cubic  : 最平滑，但平台段可能過衝
f = PchipInterpolator(r_unique, y_unique)

# 5. 產生均勻新網格（例如每 5 km 一個點）
r_new = np.arange(r_unique.min(), r_unique.max(), 5.0)
y_new = f(r_new)

# 6. 輸出 TSV
out = pd.DataFrame({'radius_km': r_new, 'value': y_new})
out.to_csv('model.tsv', sep='\t', index=False, float_format='%.6e')

